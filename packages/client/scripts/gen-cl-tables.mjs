#!/usr/bin/env node
// Writes src/cl/tables.ts from id's 3.21 game/q_shared.h and game/m_flash.c (fetched into
// .id-source by scripts/fetch-id-source.sh): the muzzle flash and temp entity numbers, and
// monster_flash_offset, which the client places monster muzzle flashes with.
// Usage: node packages/client/scripts/gen-cl-tables.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../../..');
const src = execFileSync('sh', [join(repo, 'scripts/fetch-id-source.sh'), 'full'], { encoding: 'utf8' }).trim();
const qshared = readFileSync(join(src, 'full/game/q_shared.h'), 'latin1');
const mflash = readFileSync(join(src, 'full/game/m_flash.c'), 'latin1');

const out = [];
out.push('// Generated by packages/client/scripts/gen-cl-tables.mjs from id\'s 3.21 game/q_shared.h and');
out.push('// game/m_flash.c. Do not edit; run the script.');
out.push('');
out.push("import type { Vec3 } from './qmath.js';");
out.push('');

// #define MZ_* and MZ2_* numbers, in q_shared.h's order
const defs = [...qshared.matchAll(/^#define\s+(MZ2?_\w+|SPLASH_\w+)\s+(\d+)/gm)];
for (const [, name, value] of defs) out.push(`export const ${name} = ${value};`);
out.push('');

// temp_event_t
const te = qshared.match(/typedef enum\s*\{([^}]*)\}\s*temp_event_t/)[1]
  .replace(/\/\/.*$/gm, '').split(',').map((s) => s.trim()).filter(Boolean);
te.forEach((name, i) => out.push(`export const ${name} = ${i};`));
out.push('');

// monster_flash_offset: floats, as the C stores them
const body = mflash.match(/monster_flash_offset\s*\[\]\s*=\s*\{([\s\S]*?)\};/)[1].replace(/\/\/.*$/gm, '');
const nums = body.split(',').map((s) => s.trim()).filter(Boolean)
  // a few entries are scaled in the source (10.6 * 1.2): a double product, stored as a float
  .map((s) => s.split('*').map(Number).reduce((a, b) => a * b));
if (nums.length % 3 || nums.some(Number.isNaN)) throw new Error('monster_flash_offset did not parse');
out.push('/** monster_flash_offset: forward, right and up from the monster, by MZ2_ number. */');
out.push('export const monsterFlashOffset: readonly Vec3[] = [');
for (let i = 0; i < nums.length; i += 3) {
  out.push(`  [${[nums[i], nums[i + 1], nums[i + 2]].map((n) => String(Math.fround(n))).join(', ')}],`);
}
out.push('];');
out.push('');
writeFileSync(join(repo, 'packages/client/src/cl/tables.ts'), out.join('\n'));
console.log(`${defs.length} defines, ${te.length} temp entities, ${nums.length / 3} flash offsets`);
